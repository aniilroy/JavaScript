
//JavaScript is dynamic typing, don't need to declare its type

// 1. Number data type, its mainly floating point and integers numbers

let age = 28;
console.log(typeof(age));

// 2. String data type, its mainly sequence of charactors and used for text

let firstName = 'Anil';
console.log(typeof(firstName));

// 3. Boolean data type, logical types that can only be true or false and used for taking decisions

let isTrue = true;
console.log(typeof(isTrue));

// 4. Undefined data, empty value

let peoples;

// 5. Null, Also means "Empty"

// 6. Symbol, unique value that can not be changed

// 7. BigInt, Larger integers

let javaScriptIsFun = true;
console.log(javaScriptIsFun);

//typeof true

console.log(typeof javaScriptIsFun);

javaScriptIsFun = 'Yes!';
console.log(typeof javaScriptIsFun);

//Null / undefined type

let year;
console.log(year);
console.log(typeof year);

year = 1997;
console.log(typeof year);

